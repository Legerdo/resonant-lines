// Reproducible source -> runtime art export: art/source/** (palette-indexed pixel sources) -> public/assets/**.png
// Usage: npm run art
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { allSheets } from '../art/source/index.ts';
import { buildManifest, buildSheet } from '../art/lib/build.ts';
import { encodePng } from './png.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const previewScale = 4;

function scaled(width: number, height: number, rgba: Uint8Array, s: number): Uint8Array {
  const out = new Uint8Array(width * s * height * s * 4);
  for (let y = 0; y < height * s; y++) {
    for (let x = 0; x < width * s; x++) {
      const si = (Math.floor(y / s) * width + Math.floor(x / s)) * 4;
      const di = (y * width * s + x) * 4;
      const a = rgba[si + 3]!;
      if (a === 0) {
        // preview-only checkerboard so transparency is visible during review
        const chk = ((Math.floor(x / 8) + Math.floor(y / 8)) & 1) === 0 ? 40 : 52;
        out[di] = chk;
        out[di + 1] = chk;
        out[di + 2] = chk + 8;
        out[di + 3] = 255;
      } else {
        out[di] = rgba[si]!;
        out[di + 1] = rgba[si + 1]!;
        out[di + 2] = rgba[si + 2]!;
        out[di + 3] = 255;
      }
    }
  }
  return out;
}

const built = allSheets().map(buildSheet);
for (const b of built) {
  const file = join(root, 'public', 'assets', b.def.dir, `${b.def.key}.png`);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, encodePng(b.width, b.height, b.rgba));
  const prev = join(root, 'art', 'preview', `${b.def.key}@${previewScale}x.png`);
  mkdirSync(dirname(prev), { recursive: true });
  writeFileSync(prev, encodePng(b.width * previewScale, b.height * previewScale, scaled(b.width, b.height, b.rgba, previewScale)));
  console.log(`${b.def.key.padEnd(18)} ${String(b.def.frames.length).padStart(3)} frames  ${b.width}x${b.height}  ${b.colors} colours`);
}
const manifest = buildManifest(built);
writeFileSync(join(root, 'public', 'assets', 'manifest.json'), JSON.stringify(manifest));
writeFileSync(join(root, 'src', 'presentation', 'art', 'manifestHash.ts'), `// generated by npm run art\nexport const MANIFEST_HASH = '${manifest.hash}';\n`);
console.log(`manifest ${manifest.hash} (${built.length} sheets)`);
