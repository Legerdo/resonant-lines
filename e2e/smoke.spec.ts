import { test, expect } from '@playwright/test';
import { boot, state, runBot, shot, waitFor } from './helpers.ts';

test('hub tutorial -> quarry -> B01 visual smoke', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', (e) => errors.push(String(e)));
  await boot(page);
  await page.getByRole('button', { name: '새 게임' }).click();
  await waitFor(page, `window.__RESONANT__.state().mode === 'play'`);
  await page.waitForTimeout(600);
  await shot(page, 'hub-antechamber');
  await page.evaluate(() => window.__RESONANT__!.turbo(4));
  await runBot(page, 'hub');
  let s = await state(page);
  expect(s.save.flags).toContain('tutorialDone');
  await page.evaluate(() => window.__RESONANT__!.turbo(1));
  await page.waitForTimeout(400);
  await shot(page, 'hub-main');
  await page.evaluate(() => window.__RESONANT__!.enter('quarry', 'fromHub'));
  await page.waitForTimeout(700);
  await shot(page, 'quarry');
  await page.evaluate(() => window.__RESONANT__!.enter('arena_B01', 'default'));
  await page.waitForTimeout(1600);
  await shot(page, 'b01-start');
  await page.evaluate(() => window.__RESONANT__!.bot('B01'));
  await page.waitForTimeout(5200);
  await shot(page, 'b01-mid');
  await page.evaluate(() => window.__RESONANT__!.turbo(3));
  await waitFor(page, `window.__RESONANT__.state().sim?.fight?.result === 'victory'`, 90_000);
  await page.evaluate(() => window.__RESONANT__!.turbo(1));
  await page.waitForTimeout(500);
  await shot(page, 'b01-victory');
  s = await state(page);
  expect(s.save.completed).toContain('B01');
  console.log('missing art', JSON.stringify(s.missingArt));
  expect(errors).toEqual([]);
});
