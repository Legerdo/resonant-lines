import type { AreaDef } from '../areaTypes.ts';

const row = (w: number, spec: [number, number, string][], fill = '.', edge = '#'): string => {
  const a = new Array<string>(w).fill(fill);
  a[0] = edge;
  a[w - 1] = edge;
  for (const [s, e, ch] of spec) for (let i = s; i <= e; i++) a[i] = ch;
  return a.join('');
};

